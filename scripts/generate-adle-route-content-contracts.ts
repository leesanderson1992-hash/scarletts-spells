import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import {
  ROUTE_CONTENT_CONTRACT_VERSION,
  routeContentContractInventory,
} from "../lib/adle/composable-lesson/route-content-contract";

const output = "docs/generated/adle-composable-lesson/route-content-contracts.json";
const contents = `${JSON.stringify({
  generatedNotice: "Generated by scripts/generate-adle-route-content-contracts.ts. Do not edit by hand.",
  version: ROUTE_CONTENT_CONTRACT_VERSION,
  scope: "Registered route/activity facts only; native validators and release authorities remain binding.",
  contracts: routeContentContractInventory(),
})}\n`;

if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== contents) throw new Error("ADLE_ROUTE_CONTENT_CONTRACT_DRIFT");
  console.log("ADLE route content contract inventory is current.");
} else {
  mkdirSync(dirname(output), { recursive: true });
  writeFileSync(output, contents);
  console.log(`Wrote ${output}`);
}
