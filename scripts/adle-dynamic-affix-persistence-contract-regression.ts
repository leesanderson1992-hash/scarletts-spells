assert(argumentsBlock, "reconciled canonical-intake function signature is missing");
assert.equal(argumentsBlock.match(/^\s*p_[a-z_]+\s+(?:uuid|text|date),?$/gm)?.length, 11, "reconciled canonical-intake function must expose exactly eleven arguments");
assert.match(migration, /Dynamic Affix candidate must request dynamic_affix_word_lab:v3/);
assert.match(migration, /v_route_id := 'dynamic_affix_word_lab';[\s\S]*v_route_version := 'v3'/);
assert.match(migration, /canonical_teaching_dictionary_suffix_profiles/);
assert.match(migration, /canonical_teaching_dictionary_suffix_members/);
assert.match(migration, /profile\.production_enabled = true/);
assert.match(migration, /member\.assignment_eligible = true/);
assert.match(migration, /Dynamic Prefix candidate requested an invalid route/);
assert.match(migration, /generic candidate requested an invalid route/);
assert.match(migration, /select \* into v_source[\s\S]*for update/);
assert.match(migration, /not found or v_source\.task_submission_id is null/);
assert.match(migration, /on conflict do nothing/);
assert.match(migration, /activated_at = coalesce\(/);
