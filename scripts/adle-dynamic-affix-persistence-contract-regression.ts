assert.doesNotMatch(migration, /base_word|D4_MOR_BASE/i, "BW-0 must not introduce Base Word behaviour");

assert.match(rollbackProof, /^begin;/m);
assert.match(rollbackProof, /^rollback;/m);
assert.match(rollbackProof, /adle_persist_canonical_intake\([\s\S]*?'dynamic_prefix_word_lab', 'v2'/);
assert.match(rollbackProof, /adle_persist_canonical_intake\([\s\S]*?'dynamic_affix_word_lab', 'v3'/);
assert.match(rollbackProof, /adle_persist_canonical_intake\([\s\S]*?'adle_word_level', 'v1'/);
